
# Functions to generate molecular classification using ensemble clustering methods

# Function: clustering.ensemble
# Input:
#      mod: MOFA model object containing integrated omics data.
#      factors.rm: vector specifying which factors to remove from the model.
#      algorithms: vector listing the clustering algorithms to be used.
#      outdir: path where results will be saved.
#      scale: boolean indicating whether to scale the data (TRUE or FALSE).
#
# Output: Similarity matrix for each k and algorithm.
#
# Description: This function creates a similarity matrix for each k and algorithm based on the MOFA model.
clustering.ensemble <- function(mod, factors.rm, algorithms, outdir, scale = FALSE) {
    # Obtain the factor matrix Z from the MOFA model
    Z <- obtain_Z(mod)
    
    # Remove specified factors from the factor matrix
    Z <- Z[, !colnames(Z) %in% factors.rm]

    # Perform consensus clustering using specified algorithms
    clust <- consensus_cluster(
        data = Z,
        nk = 2:6,                   # Number of clusters to test
        p.item = 0.85,              # Proportion of items to resample
        reps = 10000,               # Number of resampling iterations
        algorithms = algorithms,     # Clustering algorithms to use
        distance = "spearman",      # Distance metric
        scale = scale,              # Scale data if specified
        type = "robust",            # Type of consensus clustering
        file.name = paste0(outdir, "/consensus"), # Output filename for consensus
        progress = TRUE,            # Show progress during execution
        seed.data = 134             # Set seed for reproducibility
    )

    # Impute NA values generated by patient bootstrapping
    clust_input <- apply(clust, 2:4, impute_knn, data = Z, seed = 1)

    # Save the imputed clustering input for further analysis
    saveRDS(clust_input, paste0(outdir, "/clust_input.rds"))

    # Create the combined similarity matrix for each k and algorithm
    comb <- consensus_combine(clust_input, element = "matrix")

    # Save the combined similarity matrices
    saveRDS(comb, paste0(outdir, "/comb.rds"))
}

# Function: clustering.ensemble.matrix
# Input:
#      mod: MOFA model object.
#      factors.rm: vector specifying factors to remove from the model.
#      k: number of groups (clusters).
#      clust_input: clustering input object generated from consensus clustering.
#      outdir: path where results will be saved.
#
# Output: Matrix with samples as rows and a column indicating the group of each sample.
#
# Description: This function assigns consensus classes to samples based on clustering results.
clustering.ensemble.matrix <- function(mod, factors.rm, k, clust_input, outdir) {
    # Obtain the factor matrix Z from the MOFA model
    Z <- obtain_Z(mod)
    
    # Remove specified factors from the factor matrix
    Z <- Z[, !colnames(Z) %in% factors.rm]

    # Set output directory
    outdir <- paste0(outdir)

    # Impute missing values in the clustering input
    Ecomp <- impute_missing(clust_input, Z, nk = k)

    print("Obtaining consensus classes")

    # Obtain consensus classes using the CSPA method
    CSPA <- CSPA(clust_input, k = k)

    # Create a data frame with subtypes and corresponding row names
    class.matrix <- data.frame(
        "Subtype" = CSPA,
        row.names = rownames(Z)
    )

    # Save the class matrix to a file
    write.table(class.matrix,
                paste0(outdir, "/Class.matrix_", k, ".txt"),
                sep = "\t",
                row.names = TRUE,
                col.names = NA)

    return(class.matrix)  # Return the class matrix
}

# Function: coph.plot
# Input:
#     coph: named vector indicating the cophenetic correlation for each k.
#     outdir: path where the cophenetic plot will be saved.
#
# Output: Cophenetic plot indicating the cophenetic correlation values for each k.
#
# Description: This function creates a plot of cophenetic correlations for evaluating clustering quality.
coph.plot <- function(coph, outdir) {
    k <- as.numeric(names(coph))  # Extract k values from the names of the cophenetic vector

    outdir <- paste0(outdir)  # Set output directory

    # Create a data frame for plotting
    df <- data.frame(k = k, cophenetic.correlation = coph)

    # Generate the cophenetic plot
    plt <- ggplot(data = df, aes(x = k, y = cophenetic.correlation)) +
        geom_line() +
        geom_point() + 
        theme_classic() +
        theme(text = element_text(size = 18))  # Set font size for the plot

    # Save the cophenetic plot to a PDF file
    ggsave(
        plot = plt,
        filename = paste0(outdir, "/Cophenetic.pdf"),
        device = "pdf",
        dpi = 500,
        width = 5,
        height = 5
    )
}