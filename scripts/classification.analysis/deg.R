####################################################
# Script: DEG Analysis and Volcano Plot Generation
#
# Description:
#      This script performs differential expression analysis (DEG) between specific
#      subtypes (NS1, NS2, NS3) and other samples. It then generates volcano plots
#      for visualizing significant genes based on the DEG results. The script utilizes
#      the `deg.function` for performing DEG analysis, and the results are saved in output files.
#
# Requirements:
#      - Predefined environment with DEG functions from `deg.functions.R`.
#      - Configuration file (`config.tsv`) containing directory paths for working and data directories.
#      - Clinical and expression data files (`clinical_data.txt`, `expression.qual.txt`).
####################################################
# Required environment: deg.yml.

############### Library Imports ###############
# Load necessary libraries for DEG analysis and visualization

library(limma)
library(ggplot2)
library(rsample)
library(ggpubr)
library(rstatix)
library(tidyverse)
library(EnhancedVolcano)

# Load custom functions for differential expression analysis

source("functions/clustering/deg.functions.R")


############### Configuration and Directory Setup ###############
# Read configuration file (config.tsv) to obtain necessary directory paths

config <- read.csv("config/config.tsv",
sep = "\t",
header = T)

# Assign configuration keys and values
keys <- config$key
values <- config$value
names(values) <- keys
# Define working directory and data directory from config
wkdir <- values["wkdir"]
datadir <- values["datadir"]

# Check if DEG output directory exists, if not create it
if (dir.exists(paste0(wkdir, "/clustering/deg")) == F) {

    dir.create(paste0(wkdir, "/clustering/deg"))

}

# Set output directory for DEG results
outdir <- paste0(wkdir, "/clustering/deg")

############### Data Loading ###############
# Load the clinical data from the specified file

base <- read.csv(paste0(datadir, "/clinical_data.txt"),
                 sep = "\t",
                 header = T,
                 row.names = 1)

# Preprocess clinical data (convert tumor information to factors)
base$PRIMARY_TUMOR <- as.factor(gsub(" ", "_", base$PRIMARY_TUMOR))


# Load expression data from the specified file
exp <- read.table(paste0(wkdir,
"/preprocess/transcriptome/expression.qual.txt"),
    sep = "\t",
    header = T,
    row.names = 1,
    check.names = F
)


############### Subtype Definition for Analysis ###############
# Define groups for DEG analysis by creating a binary classification for each subtype


base$NS1 <- as.character(base$Subtype)
base$NS1[base$NS1 != "NS1"] <- "Other"


base$NS2 <- as.character(base$Subtype)
base$NS2[base$NS2 != "NS2"] <- "Other"

base$NS3 <- as.character(base$Subtype)
base$NS3[base$NS3 != "NS3"] <- "Other"


############### Differential Expression Analysis ###############
# Perform DEG analysis for NS1 vs Others

NS1 <- deg.function(exp,
base,
group = "NS1",
cov = "PRIMARY_TUMOR",
outdir = paste0(wkdir, "/clustering/deg"),
flag = "deg_NS1")

# Perform DEG analysis for NS2 vs Others
NS2 <- deg.function(exp,
base,
group = "NS2",
cov = "PRIMARY_TUMOR",
outdir = paste0(wkdir, "/clustering/deg"),
flag = "deg_NS2")


# Perform DEG analysis for NS3 vs Others
NS3 <- deg.function(exp,
base,
group = "NS3",
cov = "PRIMARY_TUMOR",
outdir = paste0(wkdir, "/clustering/deg"),
flag = "deg_NS3")

############### DEG Result Files Loading ###############
# Load DEG result tables from the output files generated by deg.function

NS1 <- read.table(paste0(wkdir,
"/clustering/deg/TopTable_deg_NS1_GroupNS1-GroupOther.txt"),
sep = "\t",
row.names = 1,
header = T
)

NS2 <- read.table(paste0(wkdir,
"/clustering/deg/TopTable_deg_NS2_GroupNS2-GroupOther.txt"),
sep = "\t",
row.names = 1,
header = T
)

NS3 <- read.table(paste0(wkdir,
"/clustering/deg/TopTable_deg_NS3_GroupNS3-GroupOther.txt"),
sep = "\t",
row.names = 1,
header = T
)

############### Volcano Plot Generation ###############
# Generate volcano plot for NS1 vs Others

v.NS1 <- EnhancedVolcano(NS1,
lab = rownames(NS1),
x = "logFC",
y = "adj.P.Val",
title = "NS1 vs Others",
FCcutoff = 0,
pCutoff = 0.1,
subtitle = NULL,
boxedLabels = TRUE,
drawConnectors = TRUE,
labSize = 6.0,
xlim = c(min(NS1[["logFC"]], na.rm = TRUE) - 0.5, max(NS1[["logFC"]], na.rm = TRUE) +
0.5),
ylim = c(0, max(-log10(NS1[["adj.P.Val"]]), na.rm = TRUE) + 1))

# Save volcano plot for NS1
ggsave(v.NS1,
filename = paste0(wkdir, "/clustering/deg/Volcano_NS1.pdf"),
device = "pdf",
dpi = 500, width = 15,
height = 10
)

# Generate volcano plot for NS2 vs Others
v.NS2 <- EnhancedVolcano(NS2,
lab = rownames(NS2),
x = "logFC",
y = "adj.P.Val",
title = "SubtypeNS2 vs Others",
FCcutoff = 0,
pCutoff = 0.05,
subtitle = NULL,
boxedLabels = TRUE,
drawConnectors = TRUE,
labSize = 6.0,
xlim = c(min(NS2[["logFC"]], na.rm = TRUE) - 0.5, max(NS2[["logFC"]], na.rm = TRUE) +
0.5),
ylim = c(0, max(-log10(NS2[["adj.P.Val"]]), na.rm = TRUE) + 1))

# Save volcano plot for NS2
ggsave(v.NS2,
filename = paste0(wkdir, "/clustering/deg/Volcano_NS2.pdf"),
device = "pdf",
dpi = 500, width = 15,
height = 10
)

# Generate volcano plot for NS3 vs Others
v.NS3 <- EnhancedVolcano(NS3,
lab = rownames(NS3),
x = "logFC",
y = "adj.P.Val",
title = "SubtypeNS3 vs Subtype Others",
FCcutoff = 0,
pCutoff = 0.05,
subtitle = NULL,
boxedLabels = TRUE,
drawConnectors = TRUE,
labSize = 6.0,
xlim = c(min(NS3[["logFC"]], na.rm = TRUE) - 0.5, max(NS3[["logFC"]], na.rm = TRUE) +
0.5),
ylim = c(0, max(-log10(NS3[["adj.P.Val"]]), na.rm = TRUE) + 1))

# Save volcano plot for NS3
ggsave(v.NS3,
filename = paste0(wkdir, "/clustering/deg/Volcano_NS3.pdf"),
device = "pdf",
dpi = 500, width = 15,
height = 10
)


NS1.genes <- rownames(NS1)[NS1$adj.P.Val < 0.05 ]

NS2.genes <- rownames(NS2)[NS2$adj.P.Val < 0.05 ]

NS3.genes <- rownames(NS3)[NS3$adj.P.Val < 0.10 ]


NS1_filter <- NS1[NS1$adj.P.Val < 0.05 ,]
NS2_filter <- NS2[NS2$adj.P.Val < 0.05 ,]
NS3_filter <- NS3[NS3$adj.P.Val < 0.10 ,]


# Write filtered deg table
write.table(NS1_filter,
paste0(outdir, "/Table_NS1_filter.txt"),
sep = "\t",
row.names = T,
col.names = NA)

write.table(NS2_filter,
paste0(outdir, "/Table_NS2_filter.txt"),
sep = "\t",
row.names = T,
col.names = NA)

write.table(NS3_filter,
paste0(outdir, "/Table_NS3_filter.txt"),
sep = "\t",
row.names = T,
col.names = NA)



NS.genes <- c(NS1.genes,NS2.genes,NS3.genes)

exp <- exp[NS.genes,]



write.table(exp,
paste0(wkdir,
"/clustering/deg/Expression.NS.txt"),
sep = "\t",
row.names= T,
col.names= NA)




# write DEGS
NS1 <- read.table(paste0(wkdir,
"/clustering/deg/Table_NS1_filter.txt"),
sep = "\t",
row.names = 1,
header = T
)

NS2 <- read.table(paste0(wkdir,
"/clustering/deg/Table_NS2_filter.txt"),
sep = "\t",
row.names = 1,
header = T
)

NS3 <- read.table(paste0(wkdir,
"/clustering/deg/Table_NS3_filter.txt"),
sep = "\t",
row.names = 1,
header = T
)


NSs <- merge(NS1,NS2,by = "row.names", all = T)
NSs <- merge(NSs,NS3,by.x = "Row.names", by.y = "row.names", all = T)



colnames(NSs) <- c("Gene.Symbol","NS1.logFC","NS1.AveExpr", "NS1.t.statistic", "NS1.P.Value",
"NS1.adj.P.Val","NS1.B.statistics", "NS2.logFC","NS1.AveExpr", "NS2.t.statistic", "NS2.P.Value",
"NS2.adj.P.Val","NS2.B.statistics", "NS3.logFC","NS3.AveExpr", "NS3.t.statistic", "NS3.P.Value",
"NS3.adj.P.Val","NS3.B.statistics") 

write.table(NSs,
paste0(wkdir,
"/clustering/deg/All.DEGs.txt"),
sep = "\t",
row.names= F,
col.names= T,
na = "NS")
