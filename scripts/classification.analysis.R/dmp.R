####################################################
# Script: DMP Analysis for Methylation Data
#
# Description:
#      This script performs differential meyhylation analysis  on methylation data
#      for different subtypes (NS1, NS2, NS3) compared to other samples. It loads necessary
#      libraries and functions, reads the required configuration and data files, and processes
#      the methylation data to generate a list of significant probes. Results are saved in
#      designated output files.
#
# Requirements:
#      - Predefined environment with DMP functions from `deg.functions.R`.
#      - Configuration file (`config.tsv`) containing directory paths for working and data directories.
#      - Clinical data file (`clinical_data.txt`) and methylation data file (`methylation.qual.txt`).
#      - Methylation annotation file from the Infinium Methylation EPIC array.
####################################################
# Required environment: deg.yml.

library(limma)
library(ggplot2)
library(rsample)
library(ggpubr)
library(rstatix)
library(tidyverse)


# Load custom functions for differential expression analysis and methylation anotation
source("functions/clustering/deg.functions.R")
source("functions/clustering/common.functions.R")


############### Configuration and Directory Setup ###############
# Read configuration file (config.tsv) to obtain necessary directory paths

config <- read.csv("config/config.tsv",
sep = "\t",
header = T)

# Assign configuration keys and values
keys <- config$key
values <- config$value
names(values) <- keys

# Define working directory and data directory from config
wkdir <- values["wkdir"]
datadir <- values["datadir"]


# Check if DMP output directory exists, if not create it
if (dir.exists(paste0(wkdir, "/clustering/dmp")) == F) {

    dir.create(paste0(wkdir, "/clustering/dmp"))

}


############### Data Loading ###############
# Load the clinical data from the specified file
base <- read.csv(paste0(datadir, "/clinical_data.txt"),
                 sep = "\t",
                 header = T,
                 row.names = 1)

# Preprocess clinical data (convert tumor information to factors)
base$PRIMARY_TUMOR <- as.factor(gsub("_", " ", base$PRIMARY_TUMOR))

# Load methylation data from the specified file

data <- read.table(paste0(wkdir,
"/preprocess/methylome/methylation.qual.txt"),
    sep = "\t",
    header = T,
    row.names = 1,
    check.names = F
)

base$PRIMARY_TUMOR <- as.factor(gsub(" ", "_", base$PRIMARY_TUMOR))



# Load methylation annotation data

epic <- read.csv(paste0(datadir,
"/methylome/anotation/infinium-methylationepic-v-1-0-b5-manifest-file.csv"),
                       sep = ",",
                       header = T,
                       skip = 7)
    
# Transform methylation annotation matrix using a custom function
met_anot <- create.met.anot(epic)


############### Subtype Definition for Analysis ###############
# Define groups for DMP analysis by creating a binary classification for each subtype

base$NS1 <- as.character(base$Subtype)
base$NS1[base$NS1 != "NS1"] <- "Other"


base$NS2 <- as.character(base$Subtype)
base$NS2[base$NS2 != "NS2"] <- "Other"

base$NS3 <- as.character(base$Subtype)
base$NS3[base$NS3 != "NS3"] <- "Other"



############### Differential Methylation Analysis ###############
# Perform DMP analysis for NS1 vs Others
NS1 <- deg.function(data,
base,
group = "NS1",
cov = "PRIMARY_TUMOR",
outdir = paste0(wkdir, "/clustering/dmp"),
flag = "dmp_NS1")

# Perform DMP analysis for NS2 vs Others
NS2 <- deg.function(data,
base,
group = "NS2",
cov = "PRIMARY_TUMOR",
outdir = paste0(wkdir, "/clustering/dmp"),
flag = "dmp_NS2")
# Perform DMP analysis for NS3 vs Others
NS3 <- deg.function(data,
base,
group = "NS3",
cov = "PRIMARY_TUMOR",
outdir = paste0(wkdir, "/clustering/dmp"),
flag = "dmp_NS3")



############### DMP Result Files Loading ###############
# Load DMP result tables from the output files generated by deg.function

NS1 <- read.table(paste0(wkdir,
"/clustering/dmp/TopTable_dmp_NS1_GroupNS1-GroupOther.txt"),
sep = "\t",
row.names = 1,
header = T
)

NS2 <- read.table(paste0(wkdir,
"/clustering/dmp/TopTable_dmp_NS2_GroupNS2-GroupOther.txt"),
sep = "\t",
row.names = 1,
header = T
)

NS3 <- read.table(paste0(wkdir,
"/clustering/dmp/TopTable_dmp_NS3_GroupNS3-GroupOther.txt"),
sep = "\t",
row.names = 1,
header = T
)

############### Filtering Significant Probes ###############
# Annotate results with methylation data annotation

NS1 <- anotation(NS1,
met_anot,
outdir = paste0(wkdir, "/clustering/dmp"),
flag = "NS1")

NS2 <- anotation(NS2,
met_anot,
outdir = paste0(wkdir, "/clustering/dmp"),
flag = "NS2")

NS3 <- anotation(NS3,
met_anot,
outdir = paste0(wkdir, "/clustering/dmp"),
flag = "NS3")

# Filter significant probes based on adjusted p-value and log fold change
NS1 <- NS1$ID[NS1$adj.P.Val < 0.05 &  abs(NS1$logFC) > 1]
NS2 <- NS2$ID[NS2$adj.P.Val < 0.05 &  abs(NS2$logFC) > 1]
NS3 <- NS3$ID[NS3$adj.P.Val < 0.05 &  abs(NS3$logFC) > 1]

# Combine significant probes across subtypes
probes <- c(NS1,NS2,NS3)

# Create a subset of the methylation data for significant probes
met.NS <- data[unique(probes),]



############### Output Results ###############
# Save the significant methylation data for the defined probes

write.table(met.NS,
paste0(wkdir,
"/clustering/dmp/Methylation.NS.txt"),
sep = "\t",
row.names= T,
col.names= NA)
