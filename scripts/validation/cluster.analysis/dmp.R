###############################################################################
# Script: Differential Methylation Probe (DMP) Analysis
#
# Description:
#     This script performs differentially methylated probe (DMP) analysis 
#     between subtypes (NS1, NS2, NS3) and generates annotated DMP results.
#
# Inputs:
#     - Methylation data: methylation_all.tsv
#     - Validation dataset: Base_validation.subtype.tsv
#     - Configuration file: config.tsv
#
# Outputs:
#     - DMP results for NS1, NS2, NS3
#     - Annotated DMP tables with gene and CpG site information
#
# Required environment: `deg`
#
############################################################################
