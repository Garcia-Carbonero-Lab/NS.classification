
# This script processes gene expression data to identify master regulators using the VIPER algorithm.
# The script takes an ARACNe-inferred regulatory network, processes it, prunes the network,
# and then computes the activity of master regulators in gene expression samples.
#
# Requirements:
# - VIPER must be installed and available.
# - Preprocessed ARACNe network results and a quality-adjusted expression matrix must be available.
# - Configuration file (config/config.tsv) must define the working directory and data directory paths.
#
# Inputs:
# - expression.qual.txt: Quality-adjusted gene expression matrix.
# - concatenated_networks.tsv: Consolidated ARACNe network file.
#
# Outputs:
# - Pruned regulon file containing transcription factor (TF)-gene relationships.
# - VIPER enrichment scores for master regulators across samples.
# Required environment: 'viper.yml' (containing prerequiste libraries).

####################################################
# Load required libraries and functions
####################################################


####################################################
# Load required libraries and functions
####################################################

# Load the VIPER package, which is essential for master regulator analysis

library(viper)
# Load additional custom functions required for VIPER analysis, such as 'RegProcess'
source("functions/master_regulators/viper.functions.R")


####################################################
# Load configuration and set directories
####################################################

# Load the configuration file to access working and data directories

config <- read.csv("config/config.tsv",
    sep = "\t",
    header = T
)
# Extract key-value pairs from the configuration file
keys <- config$key
values <- config$value
names(values) <- keys
# Set the working directory and data directory based on the configuration file

wkdir <- values["wkdir"]
datadir <- values["datadir"]


####################################################
# Load the expression data
####################################################

# Open the quality-adjusted expression matrix
# This file contains gene expression levels with genes as rows and samples as columns

expression <- read.table(paste0(wkdir, "/preprocess/transcriptome/expression.qual.txt"),
sep = '\t',
header = T,
row.names = 1,
check.names = F
)


####################################################
# Create output directories if needed
####################################################

# Check if the directory for VIPER analysis exists; if not, create it
# This directory will store the results from VIPER, such as pruned regulon files and activity scores

if (dir.exists(paste0(wkdir, "/master_regulators/viper")) == F) {
  dir.create(paste0(wkdir, "/master_regulators/viper"))
}


####################################################
# Run RegProcess to generate and prune the regulon
####################################################

# The 'RegProcess' function processes the ARACNe-generated network and prunes it.
# It saves both the unpruned and pruned regulon objects for further analysis.


RegProcess(paste0(wkdir, "/master_regulators/aracne/concatenated_networks.tsv"),
as.matrix(expression),
out.dir = paste0(wkdir, "/master_regulators/viper/"),
out.name = "neuroendocrine")


####################################################
# Run VIPER analysis using the pruned regulon
####################################################

# Load the pruned regulon generated by the 'RegProcess' function
net <- readRDS(paste0(wkdir, "/master_regulators/viper/neuroendocrinepruned.rds"))


# Run VIPER to calculate the activity of master regulators using the expression matrix and the pruned regulon
# 'viper' calculates the enrichment of master regulator activity in each sample based on the regulatory network
viper.res <- viper(as.matrix(expression), net, method = "rank")



####################################################
# Save VIPER results
####################################################

# Write the VIPER results (master regulator activity scores) to a text file
write.table(viper.res,
paste0(wkdir, "/master_regulators/viper/viper.results.txt"),
sep = "\t",
row.names = T,
col.names = NA,
quote = F
)
